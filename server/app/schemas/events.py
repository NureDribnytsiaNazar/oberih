"""Схеми охорони, подій пристроїв, архіву подій і тривог."""

import enum
import uuid
from datetime import datetime
from decimal import Decimal
from typing import Annotated, Any, Literal

from pydantic import AwareDatetime, BaseModel, Field, field_validator

from app.models.enums import (
    AckAction,
    ActionSource,
    AlarmLevel,
    AlarmStatus,
    AuthMethod,
    CommandStatus,
    CommandType,
    EventType,
    FacilityMode,
)
from app.schemas.common import Confirmation, ORMModel

# Джерела, з яких користувач може надіслати команду через API.
USER_SOURCES = {ActionSource.WEB, ActionSource.MOBILE, ActionSource.API}


def _user_source(source: ActionSource) -> ActionSource:
    if source not in USER_SOURCES:
        raise ValueError("source must be web, mobile or api")
    return source


# --- Охорона -----------------------------------------------------------------


class ArmMode(str, enum.Enum):
    """Режим постановки: повна охорона або «Вдома» (лише периметр)."""

    AWAY = "away"
    HOME = "home"


class ArmRequest(BaseModel):
    """Команда постановки на охорону."""

    mode: ArmMode
    source: ActionSource = ActionSource.API

    _check_source = field_validator("source")(_user_source)


class DisarmRequest(BaseModel):
    """Команда зняття з охорони з повторним підтвердженням."""

    confirmation: Confirmation | None = None
    source: ActionSource = ActionSource.API

    _check_source = field_validator("source")(_user_source)


class FacilityStateOut(BaseModel):
    """Поточний режим охорони об'єкта."""

    facility_id: uuid.UUID
    mode: FacilityMode
    mode_changed_at: datetime


class ArmingLogOut(ORMModel):
    """Запис журналу постановки та зняття з охорони."""

    id: int
    user_id: uuid.UUID | None
    from_mode: FacilityMode
    to_mode: FacilityMode
    source: ActionSource
    auth_method: AuthMethod | None
    ip_address: str | None
    created_at: datetime


# --- Події від пристроїв -----------------------------------------------------

# Події, які формує сам вузол; node_offline/node_online формує сервер.
DEVICE_EVENT_TYPES = {
    EventType.OPENED,
    EventType.CLOSED,
    EventType.MOTION,
    EventType.TAMPER,
    EventType.TAMPER_RESTORED,
}


class DeviceEventIn(BaseModel):
    """Подія з буфера вузла."""

    channel: Annotated[int, Field(ge=0, le=63)] = Field(
        description="Канал датчика на вузлі"
    )
    event_type: EventType
    seq: Annotated[int, Field(ge=0)] = Field(
        description="Порядковий номер події на вузлі (наскрізний)"
    )
    occurred_at: AwareDatetime
    payload: dict[str, Any] | None = None

    @field_validator("event_type")
    @classmethod
    def _device_event(cls, value: EventType) -> EventType:
        if value not in DEVICE_EVENT_TYPES:
            raise ValueError("this event type is generated by the server")
        return value


class DeviceEventBatch(BaseModel):
    """Пакет подій (у т. ч. буфер, накопичений без зв'язку)."""

    events: list[DeviceEventIn] = Field(min_length=1, max_length=200)


class DeviceEventResult(BaseModel):
    """Результат обробки однієї події пакета."""

    seq: int
    channel: int
    status: Literal["accepted", "duplicate"]


class DeviceEventsResult(BaseModel):
    """Результат приймання пакета."""

    accepted: int = Field(description="Нових подій записано в архів")
    duplicates: int = Field(description="Повторних подій відкинуто")
    last_seq: int
    results: list[DeviceEventResult] = Field(default_factory=list)


class HeartbeatIn(BaseModel):
    """Службове повідомлення вузла (опитування).

    Усі поля необов'язкові: вузли попередніх версій надсилають лише
    firmware_version або порожнє тіло.
    """

    firmware_version: Annotated[str, Field(max_length=32)] | None = None
    acked_command_ids: list[uuid.UUID] = Field(
        default_factory=list,
        max_length=50,
        description="Команди, які вузол отримав (виконав або відхилив)",
    )
    mode: FacilityMode | None = Field(
        default=None, description="Режим локального автомата вузла (ІК-1)"
    )
    config_version: Annotated[int, Field(ge=0)] | None = Field(
        default=None, description="Версія конфігурації, що діє на вузлі"
    )
    buffer_depth: Annotated[int, Field(ge=0)] | None = Field(
        default=None, description="Скільки подій чекає надсилання в буфері вузла"
    )


class NodeCommandOut(BaseModel):
    """Підписана команда для вузла.

    payload — рядок канонічного JSON: вузол перевіряє підпис саме над цими
    байтами, а потім розбирає їх. Час — у секундах Unix (UTC).
    """

    id: uuid.UUID
    type: CommandType
    payload: str
    nonce: int
    issued_at: int
    expires_at: int
    signature: str = Field(description="HMAC-SHA256 у шістнадцятковому вигляді")


class NodeConfigOut(BaseModel):
    """Конфігурація вузла; застосовується, якщо config_version більша за чинну."""

    exit_delay_s: int
    entry_delay_s: int
    poll_interval_s: int
    debounce_ms: int
    pir_lockout_s: int
    config_version: int


class HeartbeatOut(BaseModel):
    """Відповідь вузлу: час сервера, інтервал опитування, режим, команди."""

    server_time: datetime
    poll_interval_s: int
    facility_mode: FacilityMode
    server_epoch: int | None = Field(
        default=None, description="Час сервера в секундах Unix (для вузла)"
    )
    commands: list[NodeCommandOut] = Field(default_factory=list)
    config: NodeConfigOut | None = None
    last_seq: int | None = Field(
        default=None,
        description="Найбільший seq вузла в архіві (якщо NVS вузла очищено)",
    )


class NodeCommandAdminOut(ORMModel):
    """Команда в черзі вузла (для власника й монтажника)."""

    id: uuid.UUID
    command_type: CommandType
    payload: dict[str, Any]
    nonce: int
    issued_at: datetime
    expires_at: datetime
    delivered_at: datetime | None
    acked_at: datetime | None
    status: CommandStatus


# --- Архів подій і тривоги ---------------------------------------------------


class Measurement(BaseModel):
    """Фізична величина з корисного навантаження події в одиницях користувача."""

    name: str
    value: Decimal
    unit: str


class EventOut(ORMModel):
    """Подія з архіву: час в UTC і місцевий час користувача."""

    id: int
    node_id: uuid.UUID
    sensor_id: uuid.UUID | None
    event_type: EventType
    seq: int | None
    occurred_at: datetime
    received_at: datetime
    payload: dict[str, Any] | None
    time_local: datetime | None = None
    time_local_text: str | None = None
    measurements: list[Measurement] = []


class AlarmOut(ORMModel):
    """Тривога та стан її обробки."""

    id: uuid.UUID
    facility_id: uuid.UUID
    zone_id: uuid.UUID | None
    level: AlarmLevel
    status: AlarmStatus
    confidence: Decimal
    is_false: bool | None
    opened_at: datetime
    closed_at: datetime | None
    opened_at_local: datetime | None = None
    opened_at_text: str | None = None


class IncidentSummaryOut(ORMModel):
    """Стисла хронологія інциденту: факти окремо від припущень."""

    id: uuid.UUID
    alarm_id: uuid.UUID
    language: str
    facts: str
    assumptions: str
    model_name: str
    created_at: datetime


class AcknowledgeRequest(BaseModel):
    """Дія користувача щодо тривоги."""

    action: AckAction
    confirmation: Confirmation | None = None
    comment: Annotated[str, Field(max_length=1000)] | None = None
